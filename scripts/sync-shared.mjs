#!/usr/bin/env node
/**
 * Copies the pure TypeScript the ai-tutor Edge Function needs from src/ into
 * supabase/functions/_shared/lexicore/, so app and server run the same
 * validation and prompt code. Deno needs explicit ".ts" extensions, so relative
 * imports are rewritten. Only relative imports of .ts files are allowed: the
 * shared code must stay free of React Native, JSON and npm imports.
 *
 *   node scripts/sync-shared.mjs          write the copy
 *   node scripts/sync-shared.mjs --check  fail if the copy is out of date
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, posix, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(root, 'src');
const OUT = join(root, 'supabase/functions/_shared/lexicore');
const ENTRIES = ['domain/ai/tutorCore.ts', 'data/remote/mappers.ts'];
const check = process.argv.includes('--check');

const IMPORT = /(\bfrom\s+|\bimport\s+|\bimport\(\s*)(['"])([^'"]+)\2/g;

function resolveImport(fromFile, spec) {
  const base = resolve(dirname(fromFile), spec);
  for (const c of [`${base}.ts`, join(base, 'index.ts')]) if (existsSync(c)) return c;
  throw new Error(`${relative(root, fromFile)}: cannot resolve "${spec}" (only relative .ts imports are allowed in shared code)`);
}

const files = new Map(); // abs src path -> rewritten content
function visit(abs) {
  if (files.has(abs)) return;
  files.set(abs, '');
  const text = readFileSync(abs, 'utf8');
  const out = text.replace(IMPORT, (m, pre, q, spec) => {
    if (!spec.startsWith('.')) throw new Error(`${relative(root, abs)}: non-relative import "${spec}" is not allowed in shared code`);
    const target = resolveImport(abs, spec);
    visit(target);
    let rel = posix.normalize(relative(dirname(abs), target).split('\\').join('/'));
    if (!rel.startsWith('.')) rel = `./${rel}`;
    return `${pre}${q}${rel}${q}`;
  });
  files.set(abs, `// GENERATED by scripts/sync-shared.mjs from src/${relative(SRC, abs).split('\\').join('/')} — do not edit.\n${out}`);
}
for (const e of ENTRIES) visit(join(SRC, e));

const expected = new Map([...files].map(([abs, content]) => [join(OUT, relative(SRC, abs)), content]));

function listExisting(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).flatMap((n) => {
    const p = join(dir, n);
    return statSync(p).isDirectory() ? listExisting(p) : [p];
  });
}
const existing = listExisting(OUT);

if (check) {
  const problems = [];
  for (const [p, content] of expected) if (!existsSync(p) || readFileSync(p, 'utf8') !== content) problems.push(`out of date: ${relative(root, p)}`);
  for (const p of existing) if (!expected.has(p)) problems.push(`stale: ${relative(root, p)}`);
  if (problems.length) {
    console.error(`${problems.join('\n')}\nRun: npm run shared:sync`);
    process.exit(1);
  }
  console.log(`shared code up to date (${expected.size} files)`);
} else {
  for (const p of existing) if (!expected.has(p)) rmSync(p);
  for (const [p, content] of expected) {
    mkdirSync(dirname(p), { recursive: true });
    writeFileSync(p, content);
  }
  console.log(`wrote ${expected.size} shared files to ${relative(root, OUT)}`);
}
