#!/usr/bin/env node
/**
 * Copies platform-independent TypeScript from src/ to the places that need it,
 * so every runtime uses the same learning, validation and sync code:
 *
 *   edge  supabase/functions/_shared/lexicore  (Deno: imports rewritten to ".ts";
 *         only relative .ts imports allowed — no npm, React Native or JSON)
 *   web   web/src/lexicore                     (Next.js app; may import the
 *         packages listed below and JSON data)
 *
 * Each copy holds the entry files and everything they import, transitively.
 *
 *   node scripts/sync-shared.mjs          write the copies
 *   node scripts/sync-shared.mjs --check  fail if a copy is out of date
 */
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, posix, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(root, 'src');
const check = process.argv.includes('--check');

const TARGETS = [
  {
    name: 'edge',
    out: 'supabase/functions/_shared/lexicore',
    entries: ['domain/ai/tutorCore.ts', 'data/remote/mappers.ts'],
    deno: true,
    packages: [],
    json: false,
  },
  {
    name: 'web',
    out: 'web/src/lexicore',
    entries: [
      'state/studySessionCore.ts',
      'services/LearningStore.ts',
      'services/TutorService.ts',
      'data/remote/supabaseApi.ts',
      'data/remote/tutorApi.ts',
      'data/words.json',
      'domain/analytics.ts',
      'domain/ai/mistakes.ts',
      'domain/ai/lexical.ts',
      'domain/srs/queue.ts',
      'ui/tutor/compareCandidates.ts',
    ],
    deno: false,
    packages: ['@supabase/supabase-js', 'react'],
    json: true,
  },
];

const IMPORT = /(\bfrom\s+|\bimport\s+|\bimport\(\s*)(['"])([^'"]+)\2/g;

function resolveImport(fromFile, spec, target) {
  const base = resolve(dirname(fromFile), spec);
  const candidates = spec.endsWith('.json') ? [base] : [`${base}.ts`, `${base}.tsx`, join(base, 'index.ts')];
  for (const c of candidates) if (existsSync(c)) return c;
  throw new Error(`[${target.name}] ${relative(root, fromFile)}: cannot resolve "${spec}"`);
}

function build(target) {
  const files = new Map(); // abs src path -> content (null = copy bytes as-is)
  const visit = (abs) => {
    if (files.has(abs)) return;
    if (abs.endsWith('.json')) {
      if (!target.json) throw new Error(`[${target.name}] JSON imports are not allowed: ${relative(root, abs)}`);
      files.set(abs, null);
      return;
    }
    files.set(abs, '');
    const text = readFileSync(abs, 'utf8');
    const out = text.replace(IMPORT, (m, pre, q, spec) => {
      if (!spec.startsWith('.')) {
        if (target.packages.includes(spec)) return m;
        throw new Error(`[${target.name}] ${relative(root, abs)}: import "${spec}" is not allowed in shared code`);
      }
      const dep = resolveImport(abs, spec, target);
      visit(dep);
      if (!target.deno) return m;
      let rel = posix.normalize(relative(dirname(abs), dep).split('\\').join('/'));
      if (!rel.startsWith('.')) rel = `./${rel}`;
      return `${pre}${q}${rel}${q}`;
    });
    files.set(abs, `// GENERATED by scripts/sync-shared.mjs from src/${relative(SRC, abs).split('\\').join('/')} — do not edit.\n${out}`);
  };
  for (const e of target.entries) visit(join(SRC, e));
  const outDir = join(root, target.out);
  return { outDir, expected: new Map([...files].map(([abs, content]) => [join(outDir, relative(SRC, abs)), { abs, content }])) };
}

function listFiles(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).flatMap((n) => {
    const p = join(dir, n);
    return statSync(p).isDirectory() ? listFiles(p) : [p];
  });
}

let failed = false;
for (const target of TARGETS) {
  const { outDir, expected } = build(target);
  const existing = listFiles(outDir);
  if (check) {
    const problems = [];
    for (const [p, { abs, content }] of expected) {
      const want = content ?? readFileSync(abs, 'utf8');
      if (!existsSync(p) || readFileSync(p, 'utf8') !== want) problems.push(`out of date: ${relative(root, p)}`);
    }
    for (const p of existing) if (!expected.has(p)) problems.push(`stale: ${relative(root, p)}`);
    if (problems.length) {
      failed = true;
      console.error(problems.join('\n'));
    } else console.log(`[${target.name}] shared code up to date (${expected.size} files)`);
  } else {
    for (const p of existing) if (!expected.has(p)) rmSync(p);
    for (const [p, { abs, content }] of expected) {
      mkdirSync(dirname(p), { recursive: true });
      if (content === null) copyFileSync(abs, p);
      else writeFileSync(p, content);
    }
    console.log(`[${target.name}] wrote ${expected.size} files to ${target.out}`);
  }
}
if (failed) {
  console.error('Run: npm run shared:sync');
  process.exit(1);
}
